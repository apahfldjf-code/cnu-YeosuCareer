const shuf = (a, r = Math.random) => { const b = a.slice(); for (let i = b.length - 1; i > 0; i--) { const j = (r() * (i + 1)) | 0; [b[i], b[j]] = [b[j], b[i]]; } return b; };

/* 듣기 n문항: 문항 순서와 선택지 순서를 섞어서 돌려줍니다 */
export function pickListen(code, n = 5) {
  const L = LANG_BANK[code]; if (!L) return [];
  return shuf(L.listen).slice(0, n).map((t) => {
    const o = shuf(t.opts.map((text, i) => ({ text, ok: i === 0 })));
    return { lang: L.code, topic: t.topic, say: t.say, q: t.q, ko: t.ko, opts: o.map((x) => x.text), ans: o.findIndex((x) => x.ok) };
  });
}
/* 따라 말하기 n문장 */
export function pickSpeak(code, n = 3) {
  const L = LANG_BANK[code]; if (!L) return [];
  return shuf(L.speak).slice(0, n).map(([say, ko]) => ({ lang: L.code, say, ko }));
}